/**
 * Emits a runnable node:test file per tool so you can iterate on a handler and re-run ONE tool's
 * harness in isolation: `node --test workspace/<out>/harness/`. The generated tests call the same
 * runtime the pipeline used, so the two never disagree.
 */
import { mkdirSync, writeFileSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { pathToFileURL } from 'node:url';

export function emitHarnessTests({ outDir, model, targetPath, runtimePath, results }) {
  const dir = join(outDir, 'harness');
  mkdirSync(dir, { recursive: true });
  const files = [];
  const toUrl = p => pathToFileURL(p).href;
  for (const r of results) {
    const tool = model.tools.find(t => t.id === r.tool);
    const failing = r.observations.filter(o => !o.ok);
    const expectClean = failing.length === 0;
    const src = [
      `// Generated by Gristmill V2 — L1 harness for tool '${tool.id}'. Re-run: node --test <this directory>/`,
      `// It imports the REAL handler from the target module; nothing here re-implements the tool.`,
      `import test from 'node:test';`,
      `import assert from 'node:assert/strict';`,
      `import { probeTool } from ${JSON.stringify(toUrl(runtimePath))};`,
      `import { normalizeModel } from ${JSON.stringify(toUrl(join(dirname(runtimePath), '..', 'model.mjs')))};`,
      `import { loadTargetModule } from ${JSON.stringify(toUrl(join(dirname(runtimePath), '..', 'extract', 'from-module.mjs')))};`,
      ``,
      `const model = normalizeModel(await loadTargetModule(${JSON.stringify(targetPath)}));`,
      `const tool = model.tools.find(t => t.id === ${JSON.stringify(tool.id)});`,
      `const handler = model._handlers[tool.id];`,
      ``,
      `test(${JSON.stringify(`${tool.id}: handler executes under locked env + recording fakes`)}, async () => {`,
      `  const r = await probeTool(model, tool, handler);`,
      `  assert.ok(r.cases >= 1);`,
      `  const failing = r.observations.filter(o => !o.ok);`,
      expectClean
        ? `  assert.deepEqual(failing.map(o => o.check + '@' + o.case), [], 'tool was clean at audit time; a new failure is a regression');`
        : `  // At audit time these checks FAILED. Fix the handler, then flip this to assert they are gone:\n  const known = ${JSON.stringify([...new Set(failing.map(o => o.check))])};\n  for (const k of known) assert.ok(failing.some(o => o.check === k), 'expected known failure ' + k + ' (if it is gone, congratulations: delete it from known[])');`,
      `});`,
      ``,
    ].join('\n');
    const file = join(dir, `${tool.id}.test.mjs`);
    writeFileSync(file, src);
    files.push(file);
  }
  return files;
}
